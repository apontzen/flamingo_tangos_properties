"""Stacked FLAMINGO halo profiles for the tSZ thermostat paper (Peiris et al.).

This module produces the simulation measurements contributed to the tSZ thermostat
paper. It is the production version of the ad-hoc notebook cells that produced the
first delivery, ``flamingo_pressure_profiles.csv``; that table is reproduced here
bit-for-bit as deliverable ``pressure_z0.4`` (see "Verification" below), so the new
outputs and the one already in use are generated by the same code path.

The stacking itself is done by :mod:`flamingo_analysis` against a tangos database of
FLAMINGO halo profiles. What this module adds is the set of choices that define the
deliverable -- box, redshift, mass binning, units, and the halo statistics needed to
interpret each stack -- together with a self-describing JSON serialisation.


What is being measured
----------------------

For each halo, the simulation database stores a radial profile of a gas property,
computed in 50 logarithmically spaced radial shells and volume-weighted within each
shell. A *stack* is the unweighted mean of those profiles over all haloes in a mass
bin: a mean of profiles, not a profile of the mean halo. Each stack is reported on two
radial binnings, distinguished by the ``panel`` field:

``relative``
    Shells spaced logarithmically over 0.05 to 5.0 r200m, so each halo is stacked in
    units of its own r200m. This is the binning to use for anything scale-free.

``absolute``
    Shells spaced logarithmically over 0.05 to 5.0 Mpc (50 to 5000 kpc), physical, the
    same shells for every halo. Haloes of different size therefore contribute
    different parts of their structure to a given shell.

The reported ``x`` values are shell centres in log space, i.e. the geometric centre of
each shell, not the shell edges.

Empty shells are excluded from the mean rather than counted as zero. For pressure,
temperature and entropy this is the physically meaningful choice, since an empty shell
has no defined pressure; it does mean that in the sparsely populated outskirts a stack
is a mean over a shrinking subset of haloes. About 3% of shells are empty overall.
Density is the exception and is handled differently -- see "Density" below.

No selection beyond the mass cut is applied: all haloes in the bin enter the stack,
centrals and satellites alike, with no relaxedness or substructure cut.

A mass bin containing no haloes produces no stack rather than an empty one, so a mass
ladder is not guaranteed to be complete at every redshift. The only case here is the
>10^14 Msol bin at z = 2, where the box contains no such halo.


Mass binning
------------

Haloes are binned by M200m -- the mass within the radius enclosing 200 times the *mean*
matter density -- computed live from the halo catalogue. This is not the mass
definition used for pressure-profile fitting in the literature (usually M500c), and the
two are not interchangeable; any comparison must convert explicitly, using a
concentration relation consistent with the rest of the calculation.

The top bin of a mass ladder is open-ended. In JSON, its upper edge is serialised as
``null`` rather than infinity, which strict JSON cannot represent.

Because the mass bins are wide and the halo mass function is steep, a stack is not
representative of the mass at the centre of its bin: it is dominated by haloes near the
bin's lower edge. Each stack therefore carries ``n_halos`` and the mean and median
log10 M200m of its members, so the stack-effective mass can be used rather than
inferred. This matters most for the open top bin.


Units and cosmology
-------------------

Pressure is thermal pressure in erg cm^-3; the conversion from the database's internal
units is computed from pynbody rather than hardcoded. Density is gas mass density in
Msol kpc^-3. Radii are r/r200m (dimensionless) or physical Mpc. Masses are Msol.

All boxes here run the FLAMINGO fiducial D3A (DES-Y3) cosmology of Schaye et al. 2023
(arXiv:2306.04024), Tables 3-4, recorded in ``COSMOLOGY`` below. Note that this is not
the Planck cosmology used for work facing Efstathiou & McCarthy (2025); only ratios
transfer across that boundary.


Resolution and box size
-----------------------

Two resolutions appear here, and they must not be mixed in an absolute comparison:

``m8``  ``L0200N0720`` -- 200 Mpc box, 720^3 particles.
``m9``  ``L0200N0360`` -- 200 Mpc box, 360^3 particles.

The mean interparticle spacing sets the particle mass, so ``L0200N0720`` has the same
particle mass as the production m8 box ``L1000N3600``, and ``L0200N0360`` the same as
the production m9 box ``L1000N1800``. They are *not* those boxes: at 200 Mpc on a side
these have 1/125 of the production volume. The consequence is that there are no rich
clusters. The most massive halo at z = 0.4 is 10^14.65 Msol, and only 75 haloes exceed
10^14 Msol. Statements about clusters rest on tens of objects, not thousands.

The AGN variants exist only at m9. Comparing a variant to the m8 fiducial therefore
confounds feedback with resolution, so the variant deliverable also includes the m9
fiducial as a matched-resolution control: take variant-to-control ratios at fixed
resolution rather than differencing against the m8 stacks.


Density
-------

The database holds two distinct gas density profiles, and only one of them is suitable
for a hydrostatic test:

``gas_density``
    Shell mass divided by shell volume. Consistent with ``gas_mass_enclosed``, and zero
    (not undefined) in an empty shell, so empty shells enter the stack as zeros and the
    mean remains an unbiased mass estimator. **This is what we output.**

``gas_rho``
    The volume-weighted mean of the SPH density field over the particles in the shell.
    Undefined in an empty shell, and not constrained to integrate to the enclosed mass.
    Not used here.


The deliverables
----------------

``pressure_z0.4``
    The original delivery, reproduced. Pressure, m8 fiducial, z = 0.4, four mass bins.

``pressure_redshifts`` (task 1)
    Pressure, m8 fiducial, the same mass bins, at all nine available redshifts
    (z = 0 to 2). The request was for one additional redshift; the full series costs
    the same and lets the evolution be fitted rather than differenced. Note that the
    cluster stack thins out quickly with redshift -- 75 haloes above 10^14 Msol at
    z = 0.4, 35 at z = 0.75, 13 at z = 1.0 -- so ``n_halos`` should be consulted before
    using the top bin at high redshift. z = 0.75 is the last redshift with a usable
    cluster stack.

``pressure_massive_split`` (task 2)
    Pressure, m8 fiducial, z = 0.4, with the open >10^14 bin split. The split is at
    10^14.25, not the 10^14.5 originally suggested: the box's most massive halo is
    10^14.65, so a cut at 10^14.5 leaves 9 haloes above it, whereas 10^14.25 divides
    the 75 haloes into 44 and 31.

``pressure_fine_bins`` (task 3)
    Pressure, m8 fiducial, z = 0.4, with 0.25 dex bins spanning 10^13.5 to 10^14, which
    brackets the critical mass 10^13.76. The neighbouring bins are kept unchanged for
    context.

``density_z0.4`` (task 4)
    Gas density, m8 fiducial, z = 0.4, the original mass bins and radial range.

``pressure_variants`` (task 5)
    Pressure, z = 0.4, original mass bins, for the fgas-8sigma (``STRONGEST_AGN``) and
    Jet-4sigma (``JETS_STRONGER_AGN``) feedback variants, plus the m9 fiducial as a
    matched-resolution control. All m9 -- see "Resolution and box size".


JSON schema
-----------

Each deliverable is one JSON object::

    {
      "description":  what this file contains, in prose,
      "task":         which request it answers,
      "purpose":      why it was asked for,
      "generated_by": the command that produced it,
      "generated_on": UTC date,
      "quantity":     "pressure" or "density",
      "value_column": name of the per-stack value field, e.g. "pressure_erg_cm3",
      "units":        {...},
      "cosmology":    {...},
      "conventions":  {...},
      "caveats":      [ ... ],
      "stacks":       [ ... ]
    }

and each entry of ``stacks`` is::

    {
      "simulation", "variant", "resolution",     which box
      "redshift", "snapshot",                    which snapshot
      "mass_definition": "M200m",
      "M_min_log10Msol", "M_max_log10Msol",      bin edges; upper is null if open
      "mass_bin":                                human-readable label
      "n_halos",                                 haloes entering the stack
      "mean_log10_M200m", "median_log10_M200m",  stack-effective mass
      "mean_r200m_kpc",                          mean r200m of the members, physical
      "panel": "relative" | "absolute",
      "x_units": "r/r200m" | "Mpc",
      "x":            [50 shell centres],
      <value_column>: [50 stacked values]
    }


Verification
------------

``--verify`` regenerates the ``pressure_z0.4`` deliverable and compares it against the
CSV already delivered to the collaboration. Agreement is at the level of floating-point
round-off (~3e-16 fractional), confirming that this module and the original notebook
cells are the same measurement.

The comparison checks that the two tables describe the same rows in the same order
before comparing values, so a change to the mass or radial binning is reported as a
structural mismatch rather than showing up as large residuals.


Usage
-----

::

    python sz_paper_profile_extraction.py --list
    python sz_paper_profile_extraction.py --verify
    python sz_paper_profile_extraction.py --all --outdir sz_paper_profiles
    python sz_paper_profile_extraction.py --deliverable pressure_redshifts
"""

