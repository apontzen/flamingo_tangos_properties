REFERENCE_CSV = 'flamingo-tsz-thermostat/data/flamingo_pressure_profiles.csv'


def verify(reference_path=REFERENCE_CSV, rtol=1e-10):
    """Check that the pressure_z0.4 deliverable reproduces the delivered CSV.

    Returns (agrees, message).
    """
    document = build('pressure_z0.4')
    value_column = document['value_column']

    rows = []
    for s in document['stacks']:
        for x, value in zip(s['x'], s[value_column]):
            rows.append({'panel': s['panel'], 'mass_bin': s['mass_bin'],
                         'M_min_log10Msol': s['M_min_log10Msol'],
                         'M_max_log10Msol': np.inf if s['M_max_log10Msol'] is None
                                            else s['M_max_log10Msol'],
                         'x_units': s['x_units'], 'x': x, value_column: value})
    table = pd.DataFrame(rows)
    reference = pd.read_csv(reference_path).rename(
        columns={'pressure_erg_cm3': value_column})

    if len(reference) != len(table):
        return False, f"row count mismatch: reference {len(reference)}, new {len(table)}"
    for column in ['panel', 'mass_bin', 'M_min_log10Msol', 'M_max_log10Msol', 'x_units']:
        if not (reference[column].astype(str).values
                == table[column].astype(str).values).all():
            return False, f"rows do not line up: '{column}' differs"

    lines, agrees = [], True
    for column in ['x', value_column]:
        old, new = reference[column].values, table[column].values
        with np.errstate(divide='ignore', invalid='ignore'):
            worst = np.nanmax(np.abs(new - old) / np.abs(old))
        lines.append(f"  {column:>18s}: max |delta|/|ref| = {worst:.3e}")
        agrees &= bool(worst <= rtol)
    return agrees, "\n".join(lines)


