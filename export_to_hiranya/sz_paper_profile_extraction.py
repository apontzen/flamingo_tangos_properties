def _timestep_name(box, redshift):
    try:
        tsnum = TSNUM_BY_REDSHIFT[redshift]
    except KeyError:
        raise ValueError(f"No snapshot at z={redshift}; "
                         f"available: {sorted(TSNUM_BY_REDSHIFT)}") from None
    return f"{box}/%{tsnum}.hdf5", tsnum


def _profile_property_name(quantity, panel):
    """The tangos property name that flamingo_analysis will stack for this panel."""
    spec = QUANTITIES[quantity]
    name = spec['property'] + ('_r200m_relative' if panel == 'relative' else '')
    return f"{spec['particle']}_{name}"


def _halo_statistics(timestep_name, prop_name, mass_bins, _cache={}):
    """Number and mass of the haloes entering each stack.

    The halo set is defined by a joint query for the profile property alongside M200m,
    so it is exactly the set flamingo_analysis stacks, and the mass cut repeats the one
    applied there.
    """
    key = (timestep_name, prop_name)
    if key not in _cache:
        ts = db.get_timestep(timestep_name)
        _, M200m, r200m = ts.calculate_all(prop_name, MASS_NAME, 'r200m')
        _cache[key] = (M200m, r200m)
    M200m, r200m = _cache[key]

    statistics = []
    for M_min, M_max in mass_bins:
        mask = (M200m > 10 ** M_min) * (M200m < 10 ** M_max)
        n = int(mask.sum())
        statistics.append({
            'n_halos': n,
            'mean_log10_M200m': float(np.log10(M200m[mask]).mean()) if n else None,
            'median_log10_M200m': float(np.median(np.log10(M200m[mask]))) if n else None,
            'mean_r200m_kpc': float(r200m[mask].mean()) if n else None,
        })
    return statistics


def stack(quantity='pressure', box=M8_FIDUCIAL, redshift=DEFAULT_REDSHIFT,
          mass_bins=None):
    """Stack one quantity in one snapshot, and return a list of stack records.

    One record per (panel, mass bin). See the module docstring for the schema.
    """
    if mass_bins is None:
        mass_bins = MASS_BINS
    spec = QUANTITIES[quantity]
    variant, resolution = SIMULATIONS[box]
    timestep_name, tsnum = _timestep_name(box, redshift)

    # flamingo_analysis takes the log of each profile to form an error estimate, which
    # we discard; for density that means log(0) in empty shells. The mean profile we do
    # keep is unaffected, so silence the warning rather than let it reach the user.
    with np.errstate(divide='ignore', invalid='ignore'):
        table = fa.tabulate_profile_plot_data(
            spec['property'], tsnum=tsnum, box=box, particle=spec['particle'],
            rescale=spec['rescale'], ranges_override=list(mass_bins),
            mass_name=MASS_NAME,
            # The bootstrap only sets the error range, which we do not tabulate.
            # Skipping it leaves the mean profiles bit-for-bit identical, and is
            # much faster.
            get_stack_kwargs={'bootstrap': False},
        )
    table = table.rename(columns={spec['property']: spec['column']})

    records = []
    for panel in ('relative', 'absolute'):
        statistics = _halo_statistics(timestep_name,
                                      _profile_property_name(quantity, panel), mass_bins)
        for (M_min, M_max), stats in zip(mass_bins, statistics):
            rows = table[(table['panel'] == panel)
                         & (table['M_min_log10Msol'] == M_min)
                         & (table['M_max_log10Msol'] == M_max)]
            if len(rows) == 0:
                continue
            records.append({
                'simulation': box, 'variant': variant, 'resolution': resolution,
                'redshift': redshift, 'snapshot': tsnum,
                'mass_definition': MASS_DEFINITION,
                'M_min_log10Msol': float(M_min),
                'M_max_log10Msol': None if np.isinf(M_max) else float(M_max),
                'mass_bin': rows['mass_bin'].iloc[0],
                **stats,
                'panel': panel,
                'x_units': rows['x_units'].iloc[0],
                'x': rows['x'].tolist(),
                spec['column']: rows[spec['column']].tolist(),
            })
    return records


def build(name, command=None):
    """Assemble one named deliverable as a JSON-serialisable dict."""
    if name not in DELIVERABLES:
        raise ValueError(f"Unknown deliverable {name!r}; "
                         f"available: {sorted(DELIVERABLES)}")
    definition = DELIVERABLES[name]
    spec = QUANTITIES[definition['quantity']]

    stacks = []
    for box in definition['boxes']:
        for redshift in definition['redshifts']:
            stacks += stack(quantity=definition['quantity'], box=box,
                            redshift=redshift, mass_bins=definition['mass_bins'])

    caveats = list(GENERAL_CAVEATS)
    if definition['quantity'] != 'density':
        caveats.append(EMPTY_SHELL_CAVEAT)
    if len({SIMULATIONS[b][1] for b in definition['boxes']}) > 1 or \
            any(SIMULATIONS[b][1] == 'm9' for b in definition['boxes']):
        caveats.append(MIXED_RESOLUTION_CAVEAT)
    if any(np.isinf(M_max) for _, M_max in definition['mass_bins']):
        caveats.append(OPEN_TOP_BIN_CAVEAT)

    return {
        'description': _describe(name, definition),
        'task': definition['task'],
        'purpose': definition['purpose'],
        'generated_by': command or f"sz_paper_profile_extraction.py --deliverable {name}",
        'generated_on': datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d'),
        'source': "FLAMINGO halo profiles, stacked with flamingo_analysis.py "
                  "(the machinery of Pontzen et al. 2026, arXiv:2605.16483)",
        'quantity': definition['quantity'],
        'value_column': spec['column'],
        'value_description': spec['description'],
        'units': {
            'value': spec['unit'],
            'x_relative': 'r/r200m (dimensionless)',
            'x_absolute': 'Mpc (physical)',
            'mass': 'Msol', 'radius': 'kpc (physical)',
        },
        'radial_binning': RADIAL_BINNING,
        'cosmology': COSMOLOGY,
        'conventions': {
            'stack': "unweighted mean over haloes of the individual halo profiles, "
                     "each volume-weighted within its radial shells",
            'mass_definition': "M200m, the mass within the radius enclosing 200 times "
                               "the mean matter density",
            'log10_M_crit_z0.4': LOG10_M_CRIT,
        },
        'caveats': caveats,
        'n_stacks': len(stacks),
        'stacks': stacks,
    }


def _describe(name, definition):
    quantity = QUANTITIES[definition['quantity']]['description'].rstrip('.')
    boxes = ", ".join(f"{b} ({SIMULATIONS[b][0]}, {SIMULATIONS[b][1]})"
                      for b in definition['boxes'])
    redshifts = definition['redshifts']
    z = (f"z = {redshifts[0]}" if len(redshifts) == 1
         else f"z = {min(redshifts)} to {max(redshifts)} ({len(redshifts)} snapshots)")
    edges = sorted({e for bin in definition['mass_bins'] for e in bin
                    if not np.isinf(e)})
    return (f"{quantity}, stacked in bins of M200m. Simulations: {boxes}. {z}. "
            f"Mass bin edges (log10 M200m/Msol): "
            f"{', '.join(f'{e:g}' for e in edges)}, and above.")


